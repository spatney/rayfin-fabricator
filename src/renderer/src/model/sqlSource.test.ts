import { describe, expect, it } from 'vitest'
import type { ConnectorConfig } from './architecture'
import { buildSqlSource, sqlDiagram, usedTableCount } from './sqlSource'

const CONNECTOR: ConnectorConfig = { name: 'clinic', type: 'fabric-sqldatabase', operations: ['read'] }
const DIR = 'rayfin/connectors/clinic'

const fk = (constraintName: string, columnName: string, table: string, column: string) => ({
  constraintName,
  columnName,
  referencedTableSchema: 'dbo',
  referencedTableName: table,
  referencedColumnName: column
})

const METADATA = JSON.stringify({
  source: 'clinic',
  connector: 'fabric-sqldatabase',
  connectionString: 'clinic.database.fabric.microsoft.com',
  discoveredAt: '2026-10-25T03:43:58.726Z',
  schemas: [
    {
      schemaName: 'dbo',
      tables: [
        {
          tableName: 'appointments',
          columns: [
            { columnName: 'patient_id', dataType: 'int', isNullable: false },
            { columnName: 'appointment_id', dataType: 'int', isNullable: false, identity: { seed: 1, increment: 1 } },
            { columnName: 'copay_amount', dataType: 'decimal', isNullable: false, precision: 8, scale: 2, default: '((0))' },
            { columnName: 'notes', dataType: 'nvarchar', isNullable: true, maxLength: -1 }
          ],
          primaryKeyColumns: ['appointment_id'],
          foreignKeys: [fk('FK_appt_patient', 'patient_id', 'patients', 'patient_id')]
        },
        {
          tableName: 'patients',
          columns: [
            { columnName: 'patient_id', dataType: 'int', isNullable: false },
            { columnName: 'mrn', dataType: 'nvarchar', isNullable: false, maxLength: 20 },
            { columnName: 'referred_by', dataType: 'int', isNullable: true }
          ],
          primaryKeyColumns: ['patient_id'],
          foreignKeys: [fk('FK_patient_referrer', 'referred_by', 'patients', 'patient_id')]
        },
        {
          tableName: 'patient_profiles',
          columns: [
            { columnName: 'patient_id', dataType: 'int', isNullable: false },
            { columnName: 'bio', dataType: 'ntext', isNullable: true }
          ],
          primaryKeyColumns: ['patient_id'],
          foreignKeys: [fk('FK_profile_patient', 'patient_id', 'patients', 'patient_id')]
        }
      ]
    }
  ]
})

const APPOINTMENTS = `import { entity, decimal, int, one, role } from '@microsoft/rayfin-core';
import { Source } from '@microsoft/rayfin-connectors';
import type { AutoGenerated } from '@microsoft/rayfin-connectors';
import { Patients } from './Patients.js';

@role('authenticated', ['read'])
@entity()
export class Appointments extends Source({
  schema: 'dbo',
  table: 'appointments',
  primaryKey: ['appointmentId'],
}) {
  @int({ column: 'appointment_id' })
  appointmentId!: AutoGenerated<number>;

  @int({ column: 'patient_id' })
  patientId!: number;

  @decimal({ column: 'copay_amount', precision: 8, scale: 2 })
  copayAmount!: AutoGenerated<number>;

  @one(() => Patients, { sourceFields: ['patientId'], targetFields: ['patientId'] })
  patient!: Patients;
}
`

const PATIENTS = `import { entity, int, text } from '@microsoft/rayfin-core';
import { Source } from '@microsoft/rayfin-connectors';

@entity()
export class Patients extends Source({ schema: 'dbo', table: 'patients', primaryKey: ['patientId'] }) {
  @int({ column: 'patient_id' }) patientId!: number;
  @text({ max: 20 }) mrn!: string;
}
`

const FILES = [
  { path: `${DIR}/Appointments.ts`, text: APPOINTMENTS },
  { path: `${DIR}/Patients.ts`, text: PATIENTS },
  { path: `${DIR}/schema.ts`, text: 'export const schema = [];\n' }
]

const table = (source: ReturnType<typeof buildSqlSource>, name: string) => source.tables.find((t) => t.name === name)!

describe('buildSqlSource', () => {
  it('draws the discovered tables, keys and foreign keys, and marks the tables the app uses', () => {
    const source = buildSqlSource({
      connector: CONNECTOR,
      metadata: { path: `${DIR}/metadata.json`, text: METADATA },
      files: FILES
    })
    expect(source).toMatchObject({
      key: 'sql:clinic',
      origin: 'metadata',
      metadataFile: `${DIR}/metadata.json`,
      discoveredAt: '2026-10-25T03:43:58.726Z',
      warnings: []
    })
    expect(source.tables.map((t) => t.name)).toEqual(['appointments', 'patient_profiles', 'patients'])

    const appointments = table(source, 'appointments')
    expect(appointments.sql?.entity).toEqual({
      name: 'Appointments',
      file: `${DIR}/Appointments.ts`,
      grants: ['authenticated: read']
    })
    // Keys first, then the database's order.
    expect(appointments.columns.map((c) => [c.name, c.isKey, c.sql?.typeLabel])).toEqual([
      ['appointment_id', true, 'int'],
      ['patient_id', false, 'int'],
      ['copay_amount', false, 'decimal(8,2)'],
      ['notes', false, 'nvarchar(max)']
    ])
    const col = (name: string) => appointments.columns.find((c) => c.name === name)!.sql!
    expect(col('appointment_id')).toMatchObject({ generated: 'identity', mapped: true })
    expect(col('copay_amount')).toMatchObject({ generated: 'default', family: 'num' })
    expect(col('patient_id').references).toBe('patients.patient_id')
    // The entity leaves `notes` out.
    expect(col('notes')).toMatchObject({ nullable: true, mapped: false, family: 'text' })
    expect(table(source, 'patient_profiles').sql?.entity).toBeUndefined()

    expect(source.relationships.map((r) => [r.fromTable, r.fromColumn, r.fromCardinality, r.toTable])).toEqual([
      ['appointments', 'patient_id', 'Many', 'patients'],
      ['patients', 'referred_by', 'Many', 'patients'],
      // A foreign key that is the whole primary key is one-to-one.
      ['patient_profiles', 'patient_id', 'One', 'patients']
    ])

    expect(usedTableCount(source)).toBe(2)
    const used = sqlDiagram(source, true)
    expect(used.tables.map((t) => t.name)).toEqual(['appointments', 'patients'])
    expect(used.relationships.map((r) => r.name)).toEqual(['FK_appt_patient', 'FK_patient_referrer'])
    expect(sqlDiagram(source, false).relationships).toHaveLength(3)
  })

  it('names tables by schema when there are several, and flags an entity whose table wasn’t discovered', () => {
    const metadata = JSON.stringify({
      schemas: [
        { schemaName: 'dbo', tables: [{ tableName: 'orders', columns: [{ columnName: 'id', dataType: 'int' }] }] },
        {
          schemaName: 'sales',
          tables: [
            {
              tableName: 'orders',
              columns: [{ columnName: 'dbo_order', dataType: 'int' }],
              foreignKeys: [{ ...fk('FK_x', 'dbo_order', 'orders', 'id'), referencedTableSchema: 'dbo' }]
            }
          ]
        }
      ]
    })
    const source = buildSqlSource({
      connector: CONNECTOR,
      metadata: { path: `${DIR}/metadata.json`, text: metadata },
      files: [{ path: `${DIR}/Invoices.ts`, text: PATIENTS.replace('Patients', 'Invoices').replace("table: 'patients'", "table: 'invoices'") }]
    })
    expect(source.tables.map((t) => t.name)).toEqual(['dbo.orders', 'sales.orders'])
    expect(table(source, 'sales.orders').columns[0].sql?.references).toBe('dbo.orders.id')
    expect(source.relationships[0]).toMatchObject({ fromTable: 'sales.orders', toTable: 'dbo.orders' })
    expect(source.warnings).toEqual(['Invoices.ts reads the table dbo.invoices, which isn’t in the discovered tables.'])
  })

  it('falls back to the entity files when metadata.json is missing or unreadable', () => {
    const source = buildSqlSource({
      connector: CONNECTOR,
      metadata: { path: `${DIR}/metadata.json`, text: '{ not json' },
      files: FILES
    })
    expect(source.origin).toBe('entities')
    expect(source.warnings).toEqual(['metadata.json isn’t in the shape Rayfin writes, so it was skipped.'])
    expect(source.tables.map((t) => t.name)).toEqual(['appointments', 'patients'])
    const appointments = table(source, 'appointments')
    expect(appointments.columns.map((c) => [c.name, c.isKey, c.sql?.typeLabel, c.sql?.generated])).toEqual([
      ['appointment_id', true, 'int', 'auto'],
      ['patient_id', false, 'int', undefined],
      ['copay_amount', false, 'decimal', 'auto']
    ])
    expect(appointments.columns[1].sql?.references).toBe('patients.patient_id')
    expect(table(source, 'patients').columns.map((c) => c.sql?.typeLabel)).toEqual(['int', 'text(20)'])
    expect(source.relationships).toEqual([
      expect.objectContaining({ fromTable: 'appointments', fromColumn: 'patient_id', toTable: 'patients', toColumn: 'patient_id' })
    ])

    const tooLarge = buildSqlSource({
      connector: CONNECTOR,
      metadata: { path: `${DIR}/metadata.json`, text: null, problem: 'metadata.json is too large to read.' },
      files: []
    })
    expect(tooLarge).toMatchObject({ origin: 'none', tables: [], warnings: ['metadata.json is too large to read.'] })
  })
})
